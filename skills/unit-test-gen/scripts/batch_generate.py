PY_HEADER = '''\
"""AUTO-GENERATED by unit-test-gen skill. DO NOT EDIT.
Source: {source}
Regenerate with: /unit-test-gen auto
"""
import pytest
from unittest.mock import Mock, MagicMock, patch, AsyncMock
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))
sys.path.insert(0, str(Path(__file__).parent.parent))
from _helpers import BOUNDARY_VALUES, call_async, assert_approx
'''


def _py_import_path(source: str) -> str:
    """将文件路径转为 Python import 路径。"""
    return source.replace("/", ".").replace("\\", ".").removesuffix(".py")


def _parse_signature_params(sig: str) -> list[str]:
    """从函数签名字符串提取参数名列表。"""
    m = re.search(r"\((.+)\)", sig)
    if not m:
        return []

    raw_params = m.group(1)
    params = []
    for part in raw_params.split(","):
        part = part.strip()
        if not part or part in ("...", "*", "**"):
            continue
        name = part.split(":")[0].split("=")[0].strip()
        name = name.lstrip("*")
        if name and name.isidentifier():
            params.append(name)
    return params


def _infer_default_value(param_name: str) -> str:
    """根据参数名推断合理的 Python 默认值字符串。"""
    name = param_name.lower()
    if name in ("self", "cls"):
        return ""
    if name in ("logger", "log"):
        return "MagicMock()"
    if name in ("config", "cfg", "conf", "settings"):
        return "{}"
    if any(k in name for k in ("path", "dir", "file", "folder")):
        return "'/tmp/test'"
    if any(k in name for k in ("data", "array", "arr", "list", "buffer")):
        return "[]"
    if any(k in name for k in ("dict", "map", "kv")):
        return "{}"
    if any(k in name for k in ("count", "num", "index", "idx", "size", "len", "width", "height")):
        return "0"
    if any(k in name for k in ("tolerance", "eps", "threshold", "ratio", "rate")):
        return "0.1"
    if name.startswith("is_") or name.startswith("has_") or name.startswith("enable") or name.startswith("use_"):
        return "False"
    if any(k in name for k in ("name", "label", "title", "key", "tag", "type", "mode")):
        return "'test'"
    if any(k in name for k in ("output", "result", "ret", "response", "return")):
        return "{}"
    return "None"


def _build_py_mock_args(params: list[str]) -> str:
    """根据参数名构造 Python 调用参数字符串。"""
    args = []
    for p in params:
        if p in ("self", "cls"):
            continue
        val = _infer_default_value(p)
        args.append(f"{p}={val}")
    return ", ".join(args)


def _generate_py_boundary_params(func_data: dict) -> list[str]:
    """生成 Python 边界测试参数化值列表。"""
    sig = func_data.get("signature", "")
    has_float = "float" in sig.lower() or func_data.get("has_float_type", False)
    values = ["None", "''", "0", "-1", "[]", "{}"]
    if has_float:
        values.extend(["float('inf')", "float('-inf')", "float('nan')"])
    return values


def _extract_class_methods(functions: dict) -> dict[str, list[tuple[str, dict]]]:
    """按类分组方法。"""
    classes = {}
    standalone = []
    for func_key, func_data in functions.items():
        cls, method = _class_and_method(func_key)
        if cls:
            classes.setdefault(cls, []).append((method, func_data))
        else:
            standalone.append((func_key, func_data))
    if standalone:
        classes["__standalone__"] = standalone
    return classes


def _generate_py_function_tests(func_key: str, func_data: dict, source: str, import_path: str) -> str:
    """为单个 Python 函数生成测试代码。"""
    cls, method = _class_and_method(func_key)
    func_name = method if cls else func_key
    is_async = func_data.get("is_async", False)
    dimensions = func_data.get("dimensions", ["functional", "boundary"])
    has_exception = "exception" in dimensions
    has_data_integrity = "data_integrity" in dimensions

    sig = func_data.get("signature", "")
    params = _parse_signature_params(sig)
    call_params = [p for p in params if p not in ("self", "cls")]
    mock_args = _build_py_mock_args(call_params)

    lines = []

    if cls:
        call_prefix = f"_make_{cls.lower()}().{func_name}"
        if func_name == "__init__":
            call_prefix = f"{cls}"
    else:
        call_prefix = func_name

    lines.append("")
    lines.append("")
    if cls:
        lines.append(f"class Test{_camel(cls)}{_camel(func_name)}:")
    else:
        lines.append(f"class Test{_camel(func_key)}:")

    # Functional test
    lines.append("")
    lines.append("    def test_functional_normal(self):")
    lines.append(f"        \"\"\"功能性测试：正常输入。\"\"\"")
    if cls and func_name == "__init__":
        lines.append(f"        obj = {cls}(**{{}})")
        lines.append(f"        assert obj is not None")
    else:
        lines.append(f"        # 使用 mock 参数调用被测函数")
        if is_async:
            lines.append(f"        result = call_async({call_prefix}({mock_args}))")
        else:
            lines.append(f"        result = {call_prefix}({mock_args})")
        lines.append(f"        assert True  # 函数正常返回即通过")

    # Boundary test
    lines.append("")
    boundary_values = _generate_py_boundary_params(func_data)
    params_str = ", ".join(boundary_values[:8])
    if call_params:
        first_param = call_params[0]
        lines.append(f"    @pytest.mark.parametrize('boundary_val', [{params_str}])")
        lines.append(f"    def test_boundary_values(self, boundary_val):")
        lines.append(f"        \"\"\"边界测试：参数 {first_param} 的边界输入。\"\"\"")
        lines.append(f"        try:")
        # 将第一个参数替换为 boundary_val
        # 匹配 first_param=任意值 并替换为 first_param=boundary_val
        import re as _re
        boundary_mock_args = _re.sub(
            rf'\b{first_param}=[^,)]+',
            f'{first_param}=boundary_val',
            mock_args,
            count=1,
        )
        if f"{first_param}=" not in boundary_mock_args:
            if boundary_mock_args:
                boundary_mock_args += f", {first_param}=boundary_val"
            else:
                boundary_mock_args = f"{first_param}=boundary_val"
        if is_async:
            lines.append(f"            call_async({call_prefix}({boundary_mock_args}))")
        else:
            lines.append(f"            {call_prefix}({boundary_mock_args})")
        lines.append(f"        except Exception:")
        lines.append(f"            pass  # 边界输入触发异常是预期行为")
    else:
        lines.append(f"    def test_boundary_values(self):")
        lines.append(f"        \"\"\"边界测试：无参数函数。\"\"\"")
        if is_async:
            lines.append(f"        call_async({call_prefix}())")
        else:
            lines.append(f"        {call_prefix}()")

    # Exception test
    if has_exception:
        lines.append("")
        lines.append("    def test_exception_handling(self):")
        lines.append(f"        \"\"\"异常容错测试。\"\"\"")
        lines.append(f"        with patch('builtins.open', side_effect=IOError('mock error')):")
        lines.append(f"            try:")
        if is_async:
            lines.append(f"                call_async({call_prefix}({mock_args}))")
        else:
            lines.append(f"                {call_prefix}({mock_args})")
        lines.append(f"            except (IOError, OSError, Exception):")
        lines.append(f"                pass")

    # Data integrity test
    if has_data_integrity:
        lines.append("")
        lines.append("    def test_data_integrity(self):")
        lines.append(f"        \"\"\"数据完整性测试。\"\"\"")
        if is_async:
            lines.append(f"        r1 = call_async({call_prefix}({mock_args}))")
            lines.append(f"        r2 = call_async({call_prefix}({mock_args}))")
        else:
            lines.append(f"        r1 = {call_prefix}({mock_args})")
            lines.append(f"        r2 = {call_prefix}({mock_args})")
        lines.append(f"        if isinstance(r1, float) and isinstance(r2, float):")
        lines.append(f"            assert_approx(r1, r2)")
        lines.append(f"        if r1 is not None and r2 is not None:")
        lines.append(f"            assert str(type(r1)) == str(type(r2))")

    return "\n".join(lines)


def generate_py_file(source: str, file_data: dict) -> str:
    """为一个 Python 源文件生成完整的 pytest 测试文件。"""
    import_path = _py_import_path(source)
    functions = file_data.get("functions", {})

    parts = [PY_HEADER.format(source=source)]

    # Import section
    imports_needed = set()
    for func_key, func_data in functions.items():
        cls, method = _class_and_method(func_key)
        if cls:
            imports_needed.add(cls)
        else:
            imports_needed.add(func_key)

    import_lines = []
    for name in sorted(imports_needed):
        import_lines.append(f"from {import_path} import {name}")
    parts.append("\n".join(import_lines))

    # Group by class
    classes = _extract_class_methods(functions)

    for class_name, methods in classes.items():
        if class_name == "__standalone__":
            for func_key, func_data in methods:
                lines = _generate_py_function_tests(func_key, func_data, source, import_path)
                lines = "\n".join(l for l in lines.split("\n") if not l.startswith(f"from {import_path}"))
                parts.append(lines)
        else:
            parts.append("")
            parts.append("")
            parts.append(f"class Test{_camel(class_name)}:")

            # Helper to create instance
            parts.append("")
            parts.append(f"    def _make_instance(self, **kwargs):")
            parts.append(f"        \"\"\"构造 {class_name} 实例。\"\"\"")
            parts.append(f"        try:")
            parts.append(f"            return {class_name}(**kwargs)")
            parts.append(f"        except TypeError:")
            parts.append(f"            return MagicMock(spec={class_name})")

            for method_name, func_data in methods:
                is_async = func_data.get("is_async", False)
                dimensions = func_data.get("dimensions", ["functional", "boundary"])
                has_exception = "exception" in dimensions
                has_data_integrity = "data_integrity" in dimensions

                sig = func_data.get("signature", "")
                params = _parse_signature_params(sig)
                call_params = [p for p in params if p not in ("self", "cls")]
                mock_args = _build_py_mock_args(call_params)

                # Functional test
                parts.append("")
                parts.append(f"    def test_{method_name}_functional(self):")
                parts.append(f"        \"\"\"功能性测试：{method_name} 正常路径。\"\"\"")
                if method_name == "__init__":
                    parts.append(f"        instance = self._make_instance()")
                    parts.append(f"        assert instance is not None")
                else:
                    parts.append(f"        instance = self._make_instance()")
                    parts.append(f"        method = getattr(instance, '{method_name}')")
                    if is_async:
                        parts.append(f"        result = call_async(method({mock_args}))")
                    else:
                        parts.append(f"        result = method({mock_args})")
                    parts.append(f"        assert True  # 函数正常返回即通过")

                # Boundary test
                boundary_values = _generate_py_boundary_params(func_data)
                params_str = ", ".join(boundary_values[:6])
                parts.append("")
                if call_params:
                    first_param = call_params[0]
                    parts.append(f"    @pytest.mark.parametrize('boundary_val', [{params_str}])")
                    parts.append(f"    def test_{method_name}_boundary(self, boundary_val):")
                    parts.append(f"        \"\"\"边界测试：{method_name} 参数 {first_param} 边界输入。\"\"\"")
                    parts.append(f"        instance = self._make_instance()")
                    parts.append(f"        method = getattr(instance, '{method_name}')")
                    parts.append(f"        try:")
                    boundary_mock_args = mock_args.replace(
                        f"{first_param}=MagicMock()",
                        f"{first_param}=boundary_val",
                        1,
                    )
                    if f"{first_param}=" not in mock_args:
                        if mock_args:
                            boundary_mock_args = mock_args + f", {first_param}=boundary_val"
                        else:
                            boundary_mock_args = f"{first_param}=boundary_val"
                    if is_async:
                        parts.append(f"            call_async(method({boundary_mock_args}))")
                    else:
                        parts.append(f"            method({boundary_mock_args})")
                    parts.append(f"        except (TypeError, ValueError, AttributeError, KeyError, IndexError):")
                    parts.append(f"            pass")
                else:
                    parts.append(f"    def test_{method_name}_boundary(self):")
                    parts.append(f"        \"\"\"边界测试：{method_name} 无参数。\"\"\"")
                    parts.append(f"        instance = self._make_instance()")
                    parts.append(f"        method = getattr(instance, '{method_name}')")
                    if is_async:
                        parts.append(f"        call_async(method())")
                    else:
                        parts.append(f"        method()")

                # Exception test
                if has_exception:
                    parts.append("")
                    parts.append(f"    def test_{method_name}_exception(self):")
                    parts.append(f"        \"\"\"异常容错测试：{method_name}。\"\"\"")
                    parts.append(f"        instance = self._make_instance()")
                    parts.append(f"        method = getattr(instance, '{method_name}')")
                    parts.append(f"        with patch('builtins.open', side_effect=IOError('mock')):")
                    parts.append(f"            try:")
                    if is_async:
                        parts.append(f"                call_async(method({mock_args}))")
                    else:
                        parts.append(f"                method({mock_args})")
                    parts.append(f"            except Exception:")
                    parts.append(f"                pass")

                # Data integrity
                if has_data_integrity:
                    parts.append("")
                    parts.append(f"    def test_{method_name}_data_integrity(self):")
                    parts.append(f"        \"\"\"数据完整性测试：{method_name}。\"\"\"")
                    parts.append(f"        instance = self._make_instance()")
                    parts.append(f"        method = getattr(instance, '{method_name}')")
                    if is_async:
                        parts.append(f"        r1 = call_async(method({mock_args}))")
                        parts.append(f"        r2 = call_async(method({mock_args}))")
                    else:
                        parts.append(f"        r1 = method({mock_args})")
                        parts.append(f"        r2 = method({mock_args})")
                    parts.append(f"        if isinstance(r1, float) and isinstance(r2, float):")
                    parts.append(f"            assert_approx(float(r1), float(r2))")

    return "\n".join(parts)


