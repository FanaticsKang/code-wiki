# 通用工具函数
# =============================================================================


def _detect_language(source: str) -> str:
    """根据文件扩展名判断语言。"""
    ext = Path(source).suffix.lower()
    return "cpp" if ext in CPP_EXTENSIONS else "python"


def _test_path(source: str) -> Path:
    """计算测试文件路径（镜像目录结构）。"""
    p = Path(source)
    name = p.name
    if not name.startswith("test_"):
        name = f"test_{name}"
    return TEST_DIR / p.parent / name


def _class_and_method(func_key: str):
    """拆分类名和方法名。"""
    parts = func_key.rsplit(".", 1)
    if len(parts) == 2:
        return parts[0], parts[1]
    return None, func_key


def _camel(name: str) -> str:
    """将 snake_case 或含点的名字转为 CamelCase。"""
    return "".join(w.capitalize() for w in name.replace(".", "_").split("_") if w)


