CPP_HEADER = '''\
// AUTO-GENERATED by unit-test-gen skill. DO NOT EDIT.
// Source: {source}
// Regenerate with: /unit-test-gen auto

#include <gtest/gtest.h>
#include <gmock/gmock.h>

#include "test/generated_unit/_helpers.hpp"

{includes}
'''


def _cpp_include_path(source: str) -> str:
    """将源文件路径转为 C++ include 路径。"""
    p = Path(source)
    # .cpp → .h, .cc → .h, .cxx → .hxx 等
    header_ext_map = {".cpp": ".h", ".cc": ".h", ".cxx": ".hxx", ".hpp": ".hpp", ".hh": ".hh"}
    ext = p.suffix.lower()
    header_ext = header_ext_map.get(ext, ".h")
    header_name = p.stem + header_ext
    return str(p.parent / header_name) if str(p.parent) != "." else header_name


def _parse_cpp_params(sig: str) -> list[tuple[str, str]]:
    """从 C++ 函数签名提取参数 (type, name) 列表。"""
    m = re.search(r"\((.+)\)", sig)
    if not m:
        return []

    raw_params = m.group(1)
    params = []
    for part in raw_params.split(","):
        part = part.strip()
        if not part or part == "void" or part == "...":
            continue
        # 去掉默认值
        part = part.split("=")[0].strip()
        # 拆分类型和名称：最后一个词是名称，前面都是类型
        tokens = part.split()
        if len(tokens) >= 2:
            name = tokens[-1].lstrip("*&")
            type_str = " ".join(tokens[:-1])
            params.append((type_str, name))
        elif len(tokens) == 1:
            params.append(("", tokens[0].lstrip("*&")))
    return params


def _infer_cpp_default(type_str: str, param_name: str) -> str:
    """根据 C++ 参数类型和名称推断默认值。"""
    name = param_name.lower()
    type_lower = type_str.lower()

    # 按类型推断
    if "int" in type_lower:
        return "0"
    if "float" in type_lower or "double" in type_lower:
        return "0.1"
    if "bool" in type_lower:
        return "false"
    if "string" in type_lower:
        return '"test"'
    if "vector" in type_lower or "list" in type_lower:
        return "{}"
    if "map" in type_lower or "dict" in type_lower:
        return "{}"
    if "path" in type_lower or "filesystem" in type_lower:
        return '"/tmp/test"'
    if type_str.endswith("*"):
        return "nullptr"

    # 按名称推断
    if name in ("logger", "log"):
        return "nullptr"  # 需要 mock
    if name in ("config", "cfg", "conf", "settings"):
        return "{}"
    if any(k in name for k in ("path", "dir", "file", "folder")):
        return '"/tmp/test"'
    if any(k in name for k in ("data", "array", "arr", "list", "buffer")):
        return "{}"
    if any(k in name for k in ("count", "num", "index", "idx", "size", "len")):
        return "0"
    if name.startswith("is_") or name.startswith("has_"):
        return "false"
    if any(k in name for k in ("name", "label", "title", "key")):
        return '"test"'

    return "{}"  # 默认空初始化


def _build_cpp_args(params: list[tuple[str, str]]) -> str:
    """构造 C++ 函数调用参数字符串。"""
    args = []
    for type_str, name in params:
        if name in ("this",):
            continue
        val = _infer_cpp_default(type_str, name)
        args.append(val)
    return ", ".join(args)


def _generate_cpp_boundary_values(func_data: dict) -> list[str]:
    """生成 C++ 边界测试值列表。"""
    sig = func_data.get("signature", "")
    has_float = "float" in sig.lower() or "double" in sig.lower() or func_data.get("has_float_type", False)
    values = ["0", "-1", "1"]
    if has_float:
        values.extend(["0.0", "1e308", "-1e308"])
    return values


def _cpp_namespace_and_class(func_key: str):
    """拆分 C++ 的命名空间::类名::方法名。"""
    parts = func_key.split("::")
    if len(parts) >= 3:
        # namespace::Class::method
        return "::".join(parts[:-2]), parts[-2], parts[-1]
    elif len(parts) == 2:
        # Class::method 或 namespace::function
        return None, parts[0], parts[1]
    else:
        return None, None, func_key


def _generate_cpp_function_test(func_key: str, func_data: dict, source: str) -> str:
    """为单个 C++ 函数生成 gtest 测试代码。"""
    ns, cls, method = _cpp_namespace_and_class(func_key)
    dimensions = func_data.get("dimensions", ["functional", "boundary"])
    has_exception = "exception" in dimensions
    has_data_integrity = "data_integrity" in dimensions

    sig = func_data.get("signature", "")
    params = _parse_cpp_params(sig)
    call_args = _build_cpp_args(params)

    # 测试名
    test_suite = _camel(func_key.replace("::", "_")) + "Test"
    lines = []

    # 调用前缀
    if cls:
        call_prefix = (cls + "{}." if not ns else f"{ns}::{cls}{{}}.")
        call_prefix = call_prefix.rstrip() + method
        # 构造函数特殊处理
        if method == cls or method == "~" + cls:
            call_prefix = f"{cls}" if not ns else f"{ns}::{cls}"
    else:
        call_prefix = func_key

    # Functional test
    lines.append("")
    lines.append(f"TEST({test_suite}, FunctionalNormal) {{")
    lines.append(f"    // 功能性测试：正常输入")
    if cls and method != cls and not method.startswith("~"):
        lines.append(f"    {cls} obj;")
        lines.append(f"    auto result = obj.{method}({call_args});")
    elif cls and method == cls:
        lines.append(f"    {cls} obj({call_args});")
        lines.append(f"    // 构造成功即通过")
    else:
        lines.append(f"    auto result = {call_prefix}({call_args});")
    lines.append(f"    // 函数正常返回即通过")
    lines.append(f"}}")

    # Boundary test
    boundary_values = _generate_cpp_boundary_values(func_data)
    if params and boundary_values:
        first_type, first_name = params[0]
        lines.append("")
        lines.append(f"TEST({test_suite}, BoundaryValues) {{")
        lines.append(f"    // 边界测试：参数 {first_name} 的边界输入")
        for bv in boundary_values[:6]:
            # 替换第一个参数为边界值
            boundary_args_list = [_infer_cpp_default(t, n) for t, n in params]
            if boundary_args_list:
                boundary_args_list[0] = bv
            boundary_args = ", ".join(boundary_args_list)
            lines.append(f"    EXPECT_NO_THROW({{")
            if cls and method != cls:
                lines.append(f"        {cls} obj;")
                lines.append(f"        obj.{method}({boundary_args});")
            else:
                lines.append(f"        {call_prefix}({boundary_args});")
            lines.append(f"    }});")
        lines.append(f"}}")

    # Exception test
    if has_exception:
        lines.append("")
        lines.append(f"TEST({test_suite}, ExceptionHandling) {{")
        lines.append(f"    // 异常容错测试")
        lines.append(f"    EXPECT_NO_THROW({{")
        if cls and method != cls:
            lines.append(f"        {cls} obj;")
            lines.append(f"        obj.{method}({call_args});")
        else:
            lines.append(f"        {call_prefix}({call_args});")
        lines.append(f"    }});")
        lines.append(f"}}")

    # Data integrity test
    if has_data_integrity:
        lines.append("")
        lines.append(f"TEST({test_suite}, DataIntegrity) {{")
        lines.append(f"    // 数据完整性测试：确定性验证")
        if cls and method != cls:
            lines.append(f"    {cls} obj;")
            lines.append(f"    auto r1 = obj.{method}({call_args});")
            lines.append(f"    auto r2 = obj.{method}({call_args});")
        else:
            lines.append(f"    auto r1 = {call_prefix}({call_args});")
            lines.append(f"    auto r2 = {call_prefix}({call_args});")
        lines.append(f"    // 同样输入应返回同样结果")
        lines.append(f"}}")

    return "\n".join(lines)


def _extract_cpp_classes(functions: dict) -> dict[str, list[tuple[str, dict]]]:
    """将 C++ 函数按类分组（通过 :: 分隔符判断）。"""
    classes = {}
    standalone = []
    for func_key, func_data in functions.items():
        ns, cls, method = _cpp_namespace_and_class(func_key)
        if cls and method:
            full_cls = f"{ns}::{cls}" if ns else cls
            classes.setdefault(full_cls, []).append((method, func_data))
        else:
            standalone.append((func_key, func_data))
    if standalone:
        classes["__standalone__"] = standalone
    return classes


def generate_cpp_file(source: str, file_data: dict) -> str:
    """为一个 C++ 源文件生成完整的 gtest 测试文件。

    类方法使用 TEST_F（fixture 类），自由函数使用 TEST。
    """
    functions = file_data.get("functions", {})

    # Collect includes
    includes = set()
    header_path = _cpp_include_path(source)
    includes.add(f'#include "{header_path}"')

    header = CPP_HEADER.format(
        source=source,
        includes="\n".join(sorted(includes)),
    )

    parts = [header]

    # 按类分组
    classes = _extract_cpp_classes(functions)

    for class_name, methods in classes.items():
        if class_name == "__standalone__":
            # 自由函数：使用 TEST()
            for func_key, func_data in methods:
                test_code = _generate_cpp_function_test(func_key, func_data, source)
                parts.append(test_code)
        else:
            # 类方法：使用 TEST_F（fixture 类）
            fixture_name = _camel(class_name.replace("::", "_")) + "Test"
            cls_short = class_name.split("::")[-1]

            parts.append(f"class {fixture_name} : public ::testing::Test {{")
            parts.append(f"protected:")
            parts.append(f"    {cls_short} obj_;")
            parts.append(f"}};")
            parts.append("")

            for method_name, func_data in methods:
                dimensions = func_data.get("dimensions", ["functional", "boundary"])
                has_exception = "exception" in dimensions
                has_data_integrity = "data_integrity" in dimensions

                sig = func_data.get("signature", "")
                params = _parse_cpp_params(sig)
                call_args = _build_cpp_args(params)

                # Functional test
                parts.append(f"TEST_F({fixture_name}, {method_name}_FunctionalNormal) {{")
                parts.append(f"    // 功能性测试：{method_name} 正常路径")
                if method_name == cls_short:
                    # 构造函数
                    parts.append(f"    {cls_short} obj({call_args});")
                    parts.append(f"    // 构造成功即通过")
                elif method_name.startswith("~"):
                    # 析构函数 — 不单独测试
                    parts.append(f"    // 析构函数随 fixture 自动调用")
                else:
                    parts.append(f"    auto result = obj_.{method_name}({call_args});")
                    parts.append(f"    // 函数正常返回即通过")
                parts.append(f"}}")

                # Boundary test
                boundary_values = _generate_cpp_boundary_values(func_data)
                if params and boundary_values:
                    first_type, first_name = params[0]
                    parts.append(f"")
                    parts.append(f"TEST_F({fixture_name}, {method_name}_BoundaryValues) {{")
                    parts.append(f"    // 边界测试：{method_name} 参数 {first_name}")
                    for bv in boundary_values[:6]:
                        boundary_args_list = [_infer_cpp_default(t, n) for t, n in params]
                        if boundary_args_list:
                            boundary_args_list[0] = bv
                        boundary_args = ", ".join(boundary_args_list)
                        parts.append(f"    EXPECT_NO_THROW({{ obj_.{method_name}({boundary_args}); }});")
                    parts.append(f"}}")

                # Exception test
                if has_exception:
                    parts.append(f"")
                    parts.append(f"TEST_F({fixture_name}, {method_name}_ExceptionHandling) {{")
                    parts.append(f"    // 异常容错测试：{method_name}")
                    parts.append(f"    EXPECT_NO_THROW({{ obj_.{method_name}({call_args}); }});")
                    parts.append(f"}}")

                # Data integrity test
                if has_data_integrity:
                    parts.append(f"")
                    parts.append(f"TEST_F({fixture_name}, {method_name}_DataIntegrity) {{")
                    parts.append(f"    // 数据完整性测试：{method_name} 确定性验证")
                    parts.append(f"    auto r1 = obj_.{method_name}({call_args});")
                    parts.append(f"    auto r2 = obj_.{method_name}({call_args});")
                    parts.append(f"    // 同样输入应返回同样结果")
                    parts.append(f"}}")

    return "\n".join(parts) + "\n"


